using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;
using UnityEngine.SceneManagement;

namespace UniGameUI.Editor
{
    [InitializeOnLoad]
    public static class UIIdConstants
    {
        private const string Folder = "Assets/UniGameUI/Generated";
        private const string AssemblyName = "UniGameUI.Generated";
        private const string GeneratedMarker = "// <auto-generated>";
        private const string OwnerMarker = "// 場景 GUID: ";
        private const string PathMarker = "// 場景路徑: ";

        static UIIdConstants()
        {
            EditorSceneManager.sceneSaved += OnSceneSaved;
        }

        public static string Generate(UIRoot root)
        {
            UIAuthoring.CheckRoot(root);
            var issues = new List<UIIssue>();
            var path = GenerateForValidation(root, issues);
            if (issues.Count > 0)
                throw new InvalidOperationException(string.Join(Environment.NewLine, issues));
            return path;
        }

        internal static string GenerateForValidation(UIRoot root, List<UIIssue> issues)
        {
            var scenePath = root.gameObject.scene.path;
            var output = Describe(root, scenePath, issues);
            if (output.Path == null || issues.Count > 0)
                return null;

            UIAuthoring.EnsureAssetFolder(output.Path);
            if (!HasAssemblyDefinition())
            {
                var assemblyPath = $"{Folder}/{AssemblyName}.asmdef";
                File.WriteAllText(assemblyPath, $"{{\n    \"name\": \"{AssemblyName}\"\n}}\n", new UTF8Encoding(false));
                AssetDatabase.ImportAsset(assemblyPath);
            }
            if (!Matches(output.Path, output.Content))
            {
                File.WriteAllText(output.Path, output.Content, new UTF8Encoding(false));
                AssetDatabase.ImportAsset(output.Path);
            }
            var guid = AssetDatabase.AssetPathToGUID(scenePath);
            if (!string.IsNullOrEmpty(guid))
            {
                foreach (var file in Directory.EnumerateFiles(Folder, "*.cs"))
                {
                    var path = file.Replace('\\', '/');
                    if (path != output.Path && HasOwner(path, guid, null))
                        AssetDatabase.DeleteAsset(path);
                }
            }
            return output.Path;
        }

        internal static void Check(UIRoot root, string scenePath, bool checkCurrentFile, List<UIIssue> issues)
        {
            var issueCount = issues.Count;
            var output = Describe(root, scenePath, issues);
            if (!checkCurrentFile || issues.Count > issueCount)
                return;
            if (output.Path == null)
            {
                issues.Add(new UIIssue(UIIssueCode.ConstantsSceneUnsaved, "儲存場景後即可產生 UI ID 常數。",
                    context: root));
            }
            else if (!Matches(output.Path, output.Content) || !HasAssemblyDefinition())
            {
                issues.Add(new UIIssue(UIIssueCode.ConstantsOutdated,
                    $"ID 常數尚未產生或已過期。請儲存場景或產生「{output.Path}」。", context: root));
            }
        }

        private static (string Path, string Content) Describe(UIRoot root, string scenePath, List<UIIssue> issues)
        {
            if (string.IsNullOrEmpty(scenePath))
                return default;

            var type = PascalCase(Path.GetFileNameWithoutExtension(scenePath)) + "UI";
            var path = $"{Folder}/{type}.cs";
            var guid = AssetDatabase.AssetPathToGUID(scenePath);
            if (File.Exists(path) && !HasOwner(path, guid, scenePath))
            {
                AddError(issues, UIIssueCode.ConstantsFileOccupied,
                    $"常數檔案「{path}」已由另一個場景或使用者檔案占用。");
            }
            CheckSceneNames(root, scenePath, type, issues);

            var entries = root.Entries.Where(entry => entry != null && !string.IsNullOrWhiteSpace(entry.Id))
                .GroupBy(entry => entry.Id).Select(group => group.First()).ToDictionary(entry => entry.Id);
            var viewNames = CollectNames(entries.Keys, "Views", issues);
            var actions = root.Routes.Where(route => route != null).Select(route => route.Action)
                .Concat(entries.Values.Where(entry => entry.Review)
                    .SelectMany(entry => entry.Review.GetComponentsInChildren<UIButtonAction>(true))
                    .Select(binding => binding.Action));
            var actionNames = CollectNames(actions, "Actions", issues);
            var elementGroups = CollectNames(entries.Keys, "Elements", issues, "View");
            var elements = entries.Values.ToDictionary(entry => entry.Id, entry =>
            {
                var ids = entry.Review ? UIPlan.ElementsOf(entry.Review).Select(element => element.Id)
                    : Enumerable.Empty<string>();
                return CollectNames(ids, PascalCase(entry.Id) + "View", issues);
            });

            var source = new StringBuilder();
            source.AppendLine(GeneratedMarker);
            source.AppendLine("// UniGameUI 自動產生，請勿手動修改。");
            source.AppendLine(OwnerMarker + guid);
            source.AppendLine(PathMarker + scenePath);
            source.AppendLine();
            source.AppendLine("namespace UniGameUI.Generated");
            source.AppendLine("{");
            source.AppendLine($"    public static class {type}");
            source.AppendLine("    {");
            WriteConstants(source, "Views", viewNames, "        ");
            source.AppendLine();
            WriteConstants(source, "Actions", actionNames, "        ");
            source.AppendLine();
            source.AppendLine("        public static class Elements");
            source.AppendLine("        {");
            foreach (var (name, id) in elementGroups)
                WriteConstants(source, name, elements[id], "            ");
            source.AppendLine("        }");
            source.AppendLine("    }");
            source.AppendLine("}");
            return (path, source.ToString().Replace("\r\n", "\n"));
        }

        private static List<(string Name, string Id)> CollectNames(
            IEnumerable<string> ids, string owner, List<UIIssue> issues, string suffix = "")
        {
            var names = new Dictionary<string, string>(StringComparer.Ordinal);
            var output = new List<(string, string)>();
            foreach (var id in ids.Where(value => !string.IsNullOrWhiteSpace(value))
                .Distinct(StringComparer.Ordinal).OrderBy(value => value, StringComparer.Ordinal))
            {
                var name = PascalCase(id) + suffix;
                if (name == owner)
                {
                    AddError(issues, UIIssueCode.ConstantsNameConflict,
                        $"ID「{id}」產生的名稱 {name} 與所在類別同名。");
                }
                else if (!names.TryAdd(name, id))
                {
                    AddError(issues, UIIssueCode.ConstantsNameConflict,
                        $"ID「{names[name]}」與「{id}」在 {owner} 中都會產生 {name}。");
                }
                else
                    output.Add((name, id));
            }
            return output;
        }

        private static string PascalCase(string value)
        {
            var text = new StringBuilder();
            var capitalize = true;
            foreach (var character in value)
            {
                if (!char.IsLetterOrDigit(character))
                {
                    capitalize = true;
                    continue;
                }
                if (text.Length == 0 && !char.IsLetter(character))
                    text.Append('_');
                text.Append(capitalize ? char.ToUpperInvariant(character) : character);
                capitalize = false;
            }
            return text.Length == 0 ? "_" : text.ToString();
        }

        private static void WriteConstants(StringBuilder source, string type,
            List<(string Name, string Id)> constants, string indent)
        {
            source.AppendLine($"{indent}public static class {type}");
            source.AppendLine($"{indent}{{");
            foreach (var (name, id) in constants)
            {
                var literal = id.Replace("\\", "\\\\").Replace("\"", "\\\"")
                    .Replace("\r", "\\r").Replace("\n", "\\n").Replace("\t", "\\t");
                source.AppendLine($"{indent}    public const string {name} = \"{literal}\";");
            }
            source.AppendLine($"{indent}}}");
        }

        private static void CheckSceneNames(UIRoot root, string scenePath, string type, List<UIIssue> issues)
        {
            var workspaceScript = AssetDatabase.GetAssetPath(MonoScript.FromMonoBehaviour(root));
            foreach (var guid in AssetDatabase.FindAssets("t:Scene", new[] { "Assets" }))
            {
                var candidate = AssetDatabase.GUIDToAssetPath(guid);
                if (candidate == scenePath || PascalCase(Path.GetFileNameWithoutExtension(candidate)) + "UI" != type)
                    continue;
                var loaded = SceneManager.GetSceneByPath(candidate);
                var hasWorkspace = loaded.IsValid() && loaded.isLoaded
                    ? loaded.GetRootGameObjects().Any(gameObject => gameObject.GetComponentInChildren<UIRoot>(true))
                    : AssetDatabase.GetDependencies(candidate).Contains(workspaceScript);
                if (hasWorkspace)
                {
                    AddError(issues, UIIssueCode.ConstantsSceneConflict,
                        $"場景「{scenePath}」與「{candidate}」都會產生 {type}。");
                }
            }
        }

        private static bool Matches(string path, string content)
        {
            return File.Exists(path) && File.ReadAllText(path).Replace("\r\n", "\n") == content;
        }

        private static bool HasAssemblyDefinition()
        {
            return Directory.Exists(Folder) && Directory.EnumerateFiles(Folder, "*.asmdef").Any();
        }

        private static bool HasOwner(string file, string guid, string scenePath)
        {
            var header = File.ReadLines(file).Take(4).ToArray();
            return header.Length == 4 && header[0] == GeneratedMarker &&
                ((!string.IsNullOrEmpty(guid) && header[2] == OwnerMarker + guid) ||
                 (scenePath != null && header[3] == PathMarker + scenePath));
        }

        private static void AddError(List<UIIssue> issues, string code, string message)
        {
            issues.Add(new UIIssue(code, message));
        }

        private static void OnSceneSaved(Scene scene)
        {
            if (EditorApplication.isPlayingOrWillChangePlaymode || BuildPipeline.isBuildingPlayer)
                return;
            try
            {
                var root = UIAuthoring.FindWorkspace(scene);
                if (root)
                    Generate(root);
            }
            catch (Exception exception)
            {
                Debug.LogError($"UniGameUI：無法更新場景「{scene.name}」的 ID 常數。{exception.Message}");
            }
        }

        [MenuItem("Tools/UniGameUI/Generate ID Constants", priority = 32)]
        private static void GenerateFromMenu()
        {
            try
            {
                var path = Generate(UIAuthoring.FindWorkspace(SceneManager.GetActiveScene()));
                if (path == null)
                    Debug.LogWarning("UniGameUI：請先儲存場景，再產生 ID 常數。");
                else
                    Debug.Log($"UniGameUI：ID 常數位於「{path}」。");
            }
            catch (Exception exception)
            {
                Debug.LogError($"UniGameUI：{exception.Message}");
            }
        }
    }
}
